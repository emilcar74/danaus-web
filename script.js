const root = document.documentElement;
const themeMeta = document.querySelector('meta[name="theme-color"]');
const languageButton = document.querySelector(".language-button");
const themeButton = document.querySelector(".theme-button");

function applyLanguage(language) {
  const nextLanguage = language === "en" ? "en" : "es";
  root.lang = nextLanguage;
  document.querySelectorAll("[data-copy]").forEach((element) => {
    const key = element.dataset.copy;
    const translated = translations[nextLanguage]?.[key];
    if (translated) element.textContent = translated;
  });
  if (languageButton) {
    languageButton.querySelector("span").textContent = nextLanguage === "es" ? "EN" : "ES";
    languageButton.setAttribute("aria-label", nextLanguage === "es" ? "Cambiar idioma" : "Change language");
  }
  if (themeButton) {
    themeButton.setAttribute("aria-label", nextLanguage === "es" ? "Cambiar tema" : "Change theme");
  }
  localStorage.setItem("danaus-language", nextLanguage);
}

function applyTheme(theme) {
  const nextTheme = theme === "dark" ? "dark" : "light";
  root.dataset.theme = nextTheme;
  if (themeMeta) themeMeta.content = nextTheme === "dark" ? "#0e0d0c" : "#f4f1ed";
  if (themeButton) {
    themeButton.setAttribute("aria-label", root.lang === "es" ? "Cambiar tema" : "Change theme");
  }
  localStorage.setItem("danaus-theme", nextTheme);
}

const initialLanguage = localStorage.getItem("danaus-language")
  || (navigator.language.toLowerCase().startsWith("es") ? "es" : "en");
const initialTheme = localStorage.getItem("danaus-theme")
  || (window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light");

applyLanguage(initialLanguage);
applyTheme(initialTheme);

languageButton?.addEventListener("click", () => {
  applyLanguage(root.lang === "es" ? "en" : "es");
});

themeButton?.addEventListener("click", () => {
  applyTheme(root.dataset.theme === "dark" ? "light" : "dark");
});
